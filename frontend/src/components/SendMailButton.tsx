import {Button, SxProps} from "@mui/material";
import SendIcon from '@mui/icons-material/Send';

type SendMailButtonProps = {
    isEnabled: boolean;
    inProNumbers?: Array<string>
    sx?: SxProps
}

export default function SendMailButton(props: Readonly<SendMailButtonProps>) {
    const generateMailTo = () => {
        const subject = encodeURIComponent("Validated Location data for Project " + props.inProNumbers.join(", "));
        const bodyText = `PLEASE ATTACH BOTH PLM EXCEL AND THE GEOJSON GENERATED BY THE VALIDATOR BEFORE SENDING THIS EMAIL:

Dear KfW Portfolio Manager, 
This email contains validated project location data for BMZ project number(s): 
${props.inProNumbers.join(", \n")}
It was validated by the "Location Validator" ( https://mapme-initiative.github.io/project_location_model/validation.html ). You can use it yourself to check the data's validity and the plausibility of the project locations as displayed on the map. 
Yours sincerely, `;
        const body = encodeURIComponent(bodyText.replace(/\r?\n/g, "\r\n"));
        const mailtoLink = `mailto:?subject=${subject}&body=${body}`;
        window.location.href = mailtoLink;
    }
    return (
        <Button variant="contained"
            disabled={!props.isEnabled}
            endIcon={<SendIcon />} sx={props.sx}
            onClick={generateMailTo} >
            Send Email
        </Button>
    )
}
